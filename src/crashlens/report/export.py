"""Render a ScanReport as HTML, Markdown or JSON.

Every format is rendered from the same (optionally redacted) dictionary so the
three outputs always agree. HTML output escapes every value and contains no
scripts or external resources, so it is safe to open and to send to others.
"""

from __future__ import annotations

import html
import json
from datetime import datetime
from pathlib import Path
from typing import Any

from crashlens import __version__
from crashlens.core.models import ScanReport, Severity
from crashlens.repairs.catalog import REPAIRS
from crashlens.report.redact import Redactor

FORMATS = ("html", "md", "json")

_SEV_ORDER = [s.name for s in sorted(Severity, reverse=True)]
_SEV_COLOR = {
    "CRITICAL": "#8b1a1a",
    "HIGH": "#c0392b",
    "MEDIUM": "#d68910",
    "LOW": "#2471a3",
    "INFO": "#6c757d",
}


def report_data(report: ScanReport, redact: bool = True) -> dict[str, Any]:
    data = report.to_dict()
    findings = [f.to_dict() for f in report.findings]
    data["findings"] = findings
    data["recommended_repairs"] = [
        {"id": rid, "title": REPAIRS[rid].title, "what_happens": REPAIRS[rid].what_happens}
        for rid in report.recommended_repairs()
        if rid in REPAIRS
    ]
    data["crashlens_version"] = __version__
    data["redacted"] = redact
    if redact:
        data = Redactor(report.system).data(data)
    return data


def _when(iso: str | None) -> str:
    if not iso:
        return ""
    try:
        return datetime.fromisoformat(iso).strftime("%Y-%m-%d %H:%M UTC")
    except ValueError:
        return iso


# --------------------------------------------------------------------------- JSON


def render_json(data: dict[str, Any]) -> str:
    return json.dumps(data, indent=2, ensure_ascii=False)


# --------------------------------------------------------------------------- Markdown


def _md(s: Any) -> str:
    text = str(s).replace("\r", " ").replace("\n", " ")
    for ch in "\\`*_[]<>|#":
        text = text.replace(ch, "\\" + ch)
    return text


def render_markdown(data: dict[str, Any]) -> str:
    sysd = data["system"]
    out = ["# CrashLens report", ""]
    if data.get("demo"):
        out += ["> **Demo data** - this report was made from sample data, not a real PC.", ""]
    out += [
        f"- **Created:** {_md(_when(data['started_at']))}",
        f"- **System:** {_md(sysd['os_name'])} {_md(sysd['os_version'])}",
        f"- **Computer:** {_md(sysd['computer_name'])}",
        f"- **Personal details removed:** {'yes' if data['redacted'] else 'no'}",
        "",
        "## Summary",
        "",
        "| Severity | Count |",
        "|---|---|",
    ]
    out += [f"| {s.capitalize()} | {data['summary'].get(s, 0)} |" for s in _SEV_ORDER]
    out += ["", "## Findings", ""]
    if not data["findings"]:
        out.append("No problems found.")
    for f in data["findings"]:
        out += [f"### [{f['severity'].capitalize()}] {_md(f['title'])}", "", _md(f["summary"]), ""]
        if f.get("details"):
            out += [_md(f["details"]), ""]
        if f.get("last_seen"):
            out += [f"*Last seen:* {_md(_when(f['last_seen']))}", ""]
        if f["evidence"]:
            out += ["**Evidence**", ""] + [f"- {_md(e)}" for e in f["evidence"]] + [""]
        if f["recommendations"]:
            out += ["**What to do**", ""]
            out += [f"{i}. {_md(r)}" for i, r in enumerate(f["recommendations"], 1)] + [""]
    if data["recommended_repairs"]:
        out += ["## Suggested repairs", "", "Each repair runs only after you approve it.", ""]
        out += [
            f"- **{_md(r['title'])}** - {_md(r['what_happens'])}"
            for r in data["recommended_repairs"]
        ]
        out.append("")
    out += ["## Checks", "", "| Check | Status | Result |", "|---|---|---|"]
    for r in data["results"]:
        out.append(f"| {_md(r['name'])} | {_md(r['status'])} | {_md(r['message'])} |")
    out += ["", f"*Generated by CrashLens {_md(data['crashlens_version'])}.*", ""]
    return "\n".join(out)


# --------------------------------------------------------------------------- HTML

