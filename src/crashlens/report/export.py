def _h(s: Any) -> str:
    return html.escape(str(s), quote=True)


def render_html(data: dict[str, Any]) -> str:
    sysd = data["system"]
    parts = [
        "<!doctype html><html lang='en'><head><meta charset='utf-8'>",
        "<meta name='viewport' content='width=device-width,initial-scale=1'>",
        "<meta http-equiv='Content-Security-Policy' content=\"default-src 'none'; "
        "style-src 'unsafe-inline'\">",
        "<title>CrashLens report</title>",
        f"<style>{_CSS}</style></head><body><main>",
        "<h1>CrashLens report</h1>",
        f"<div class='meta'>{_h(_when(data['started_at']))} &middot; {_h(sysd['os_name'])} "
        f"{_h(sysd['os_version'])} &middot; {_h(sysd['computer_name'])} &middot; "
        f"personal details removed: {'yes' if data['redacted'] else 'no'}</div>",
    ]
    if data.get("demo"):
        parts.append("<div class='demo'>Demo data - made from sample data, not a real PC.</div>")
    parts.append("<div class='chips'>")
    for s in _SEV_ORDER:
        n = data["summary"].get(s, 0)
        if n:
            parts.append(
                f"<span class='chip' style='background:{_SEV_COLOR[s]}'>{n} {s.lower()}</span>"
            )
    parts.append("</div><h2>Findings</h2>")
    if not data["findings"]:
        parts.append("<p>No problems found.</p>")
    for f in data["findings"]:
        color = _SEV_COLOR.get(f["severity"], "#6c757d")
        parts.append(f"<section class='card' style='--sev:{color}'>")
        parts.append(f"<div class='sev'>{_h(f['severity'])}</div><h3>{_h(f['title'])}</h3>")
        parts.append(f"<p>{_h(f['summary'])}</p>")
        if f.get("details"):
            parts.append(f"<p>{_h(f['details'])}</p>")
        if f["recommendations"]:
            parts.append("<strong>What to do</strong><ol>")
            parts += [f"<li>{_h(r)}</li>" for r in f["recommendations"]]
            parts.append("</ol>")
        if f["evidence"]:
            parts.append("<div class='ev'><strong>Evidence</strong><ul>")
            parts += [f"<li>{_h(e)}</li>" for e in f["evidence"]]
            parts.append("</ul></div>")
        parts.append("</section>")
    if data["recommended_repairs"]:
        parts.append("<h2>Suggested repairs</h2><p>Each repair runs only after you approve it.</p>")
        parts.append("<table><tr><th>Repair</th><th>What happens</th></tr>")
        for r in data["recommended_repairs"]:
            parts.append(f"<tr><td>{_h(r['title'])}</td><td>{_h(r['what_happens'])}</td></tr>")
        parts.append("</table>")
    parts.append("<h2>Checks</h2><table><tr><th>Check</th><th>Status</th><th>Result</th></tr>")
    for r in data["results"]:
        parts.append(
            f"<tr><td>{_h(r['name'])}</td><td>{_h(r['status'])}</td><td>{_h(r['message'])}</td></tr>"
        )
    parts.append(
        f"</table><footer>Generated by CrashLens {_h(data['crashlens_version'])}.</footer>"
        "</main></body></html>"
    )
    return "".join(parts)


# --------------------------------------------------------------------------- API


def render(report: ScanReport, fmt: str, redact: bool = True) -> str:
    fmt = fmt.lower().lstrip(".")
    if fmt == "markdown":
        fmt = "md"
    if fmt not in FORMATS:
        raise ValueError(f"Unknown format '{fmt}'. Use one of: {', '.join(FORMATS)}")
    data = report_data(report, redact)
    return {"html": render_html, "md": render_markdown, "json": render_json}[fmt](data)


def format_for_path(path: Path) -> str:
    ext = path.suffix.lower().lstrip(".")
    return {"htm": "html", "markdown": "md"}.get(ext, ext)


def write_report(
    report: ScanReport,
    path: Path,
    fmt: str | None = None,
    *,
    redact: bool = True,
    overwrite: bool = False,
) -> Path:
    path = Path(path)
    fmt = fmt or format_for_path(path)
    text = render(report, fmt, redact)
    if path.exists() and not overwrite:
        raise FileExistsError(f"{path} already exists")
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(path)
    return path
